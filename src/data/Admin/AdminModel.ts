import { model, Schema } from 'mongoose'
import Admin from '../../types/Admin'

const schema = new Schema(
  {
    firstName: {
      type: String,
      required: true,
    },
    lastName: {
      type: String,
      required: true,
    },
    email: {
      type: String,
      required: true,
      unique: true,
    },
    password: {
      type: String,
      required: true,
    },
  },
  { timestamps: true }
)

export const AdminModel = model<Admin>('Admin', schema)
